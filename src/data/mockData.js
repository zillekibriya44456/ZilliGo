export const getGuideById = (id) => GUIDES.find(g => g.id === id);
export const getTourById = (id) => TOURS.find(t => t.id === id);
export const getGuideForTour = (tourId) => {
  const tour = getTourById(tourId);
  if (!tour) return null;
  return getGuideById(tour.guide);
};
